struct KeyGenCase {
    int tc_id;
    const char* sk_seed;
    const char* sk_prf;
    const char* pk_seed;
    const char* pk;        // PK.seed || PK.root
};

struct SignCase {
    int tg_id, tc_id;
    const char* sk;        // SK.seed || SK.prf || PK.seed || PK.root
    const char* opt_rand;  // nullptr: deterministic variant, opt_rand = PK.seed
    const char* message;
    const char* sig_sha3_256;
};

